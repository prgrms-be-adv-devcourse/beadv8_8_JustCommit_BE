-- settlement 서비스 V1: 지금 엔티티(Settlement) 기준 스키마
-- 정산 상태 · 판매자 부담금 · 재시도 칸, 회원 복제본 · outbox는 엔티티가 생길 때 다음 버전으로 추가한다.

create table settlement (
    id              bigint generated by default as identity,
    seller_order_id bigint         not null,
    seller_id       bigint         not null,
    sale_amount     numeric(19, 0) not null,
    fee             numeric(19, 0) not null,
    payout_amount   numeric(19, 0) not null,
    settled_at      timestamp(6)   not null,
    item_summary    varchar(255),
    created_at      timestamp(6),
    updated_at      timestamp(6),
    constraint pk_settlement primary key (id),
    -- 판매자 주문당 정산 1건 (엔티티 @UniqueConstraint와 같은 이름)
    constraint uk_settlement_seller_order_id unique (seller_order_id)
);

-- 판매자 정산 내역 (findBySellerIdOrderBySettledAtDesc)
create index idx_settlement_seller_id_settled_at on settlement (seller_id, settled_at desc);
