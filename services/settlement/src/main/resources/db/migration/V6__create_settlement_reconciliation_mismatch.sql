-- settlement V6: 정산 대사 불일치 기록
-- 해결은 운영자가 SQL로 resolved_at을 채운다 (docs/flows/confirm-settlement.md 「정산 대사」 해결 처리).
-- settlement를 지우는 테스트 · 운영 작업이 막히지 않게 외래 키는 두지 않는다

create table settlement_reconciliation_mismatch (
    id            bigint generated by default as identity,
    settlement_id bigint       not null,
    mismatch_type varchar(30)  not null,
    expected      text         not null,
    actual        text         not null,
    detected_at   timestamp(6) not null,
    resolved_at   timestamp(6),
    constraint pk_settlement_reconciliation_mismatch primary key (id),
    constraint ck_settlement_reconciliation_mismatch_type
        check (mismatch_type in ('UNEXPECTED_WALLET', 'MISSING_LEDGER', 'AMOUNT_MISMATCH', 'UNREFLECTED_STATUS'))
);

-- 미해결 행에만 걸리는 유니크: 매일 대사가 같은 불일치를 다시 찾아도 한 행만 남기고(ON CONFLICT DO NOTHING),
-- 해결한 뒤 같은 불일치가 다시 생기면 새 행으로 기록한다. 미해결 건수 지표도 이 인덱스로 센다
create unique index uk_settlement_reconciliation_mismatch_unresolved
    on settlement_reconciliation_mismatch (settlement_id, mismatch_type)
    where resolved_at is null;
