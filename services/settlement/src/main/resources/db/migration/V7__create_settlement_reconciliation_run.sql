-- settlement V7: 정산 대사 실행 이력
-- 마지막 성공 시각을 재시작 뒤에도 읽으려고 DB에 둔다 (미실행 알림이 EC2를 켤 때마다 울리지 않게)
-- result: SUCCEEDED(실패한 배치 없음, 대상 0건 포함), PARTIAL(일부 배치 실패),
--         FAILED(모든 배치 실패 또는 대상 조회 실패 등 예외),
--         BASELINE(실행 결과가 아님. 아래에서 배포 시각으로 한 번 넣는 기준 행)

create table settlement_reconciliation_run (
    id                 bigint generated by default as identity,
    started_at         timestamp(6) not null,
    finished_at        timestamp(6) not null,
    result             varchar(20)  not null,
    target_count       integer      not null,
    mismatch_count     integer      not null,
    failed_batch_count integer      not null,
    constraint pk_settlement_reconciliation_run primary key (id),
    constraint ck_settlement_reconciliation_run_result
        check (result in ('SUCCEEDED', 'PARTIAL', 'FAILED', 'BASELINE'))
);

-- 미실행 알림의 기준 시각 (마지막 SUCCEEDED, 없으면 BASELINE). 수집할 때마다 읽는다
create index idx_settlement_reconciliation_run_success
    on settlement_reconciliation_run (finished_at desc)
    where result in ('SUCCEEDED', 'BASELINE');

-- 기준 행: 배포 뒤 한 번도 성공하지 못해도 미실행 알림이 울리게 한다.
-- 배포 시각부터 25시간 유예가 생겨 첫 09:40 실행 전에는 울리지 않는다.
-- 실행이 아니므로 실행 횟수 지표, 실행 통계에서는 result <> 'BASELINE'으로 뺀다.
-- 시각은 다른 시각 칸과 같이 세션 시간대(앱 JVM과 같은 Asia/Seoul)의 시각으로 넣는다
insert into settlement_reconciliation_run
       (started_at, finished_at, result, target_count, mismatch_count, failed_batch_count)
values (localtimestamp, localtimestamp, 'BASELINE', 0, 0, 0);
