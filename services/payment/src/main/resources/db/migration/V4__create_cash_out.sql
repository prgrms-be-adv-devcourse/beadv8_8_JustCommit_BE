-- payment 서비스 V4: 인출 건 (#387)
-- 계좌는 신청 시점 값을 스냅샷으로 남긴다. 계좌번호는 암호문(account_no_enc)과 화면 표시용 뒤 4자리만 저장한다
-- status: PENDING(차감 후 지급 전 또는 지급 결과 미반영), COMPLETED. 나머지 상태는 #389에서 추가 (enum 칸에는 CHECK를 두지 않음)
-- attempt_count, next_attempt_at, last_error: 지급 재시도용 칸(#389). 이번 버전에서는 기본값과 null

create table cash_out (
    id              bigint generated by default as identity,
    wallet_id       bigint         not null,
    amount          numeric(19, 0) not null,
    status          varchar(30)    not null,
    idempotency_key varchar(64)    not null,
    bank_code       varchar(10)    not null,
    account_no_enc  varchar(512)   not null,
    account_last4   varchar(4)     not null,
    account_holder  varchar(50)    not null,
    requested_at    timestamp(6)   not null,
    completed_at    timestamp(6),
    attempt_count   integer        not null default 0,
    next_attempt_at timestamp(6),
    last_error      varchar(255),
    created_at      timestamp(6),
    updated_at      timestamp(6),
    constraint pk_cash_out primary key (id),
    -- 같은 지갑, 같은 멱등 키는 한 건만 (중복 인출 방지)
    constraint uk_cash_out_wallet_idempotency_key unique (wallet_id, idempotency_key),
    constraint ck_cash_out_amount_positive check (amount > 0),
    constraint fk_cash_out_wallet foreign key (wallet_id) references wallet (id)
);

-- 회원의 인출 내역 조회 (최근 순)
create index idx_cash_out_wallet_requested_at on cash_out (wallet_id, requested_at desc);
