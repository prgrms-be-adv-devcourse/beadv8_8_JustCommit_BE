-- payment 서비스 V1: 지금 엔티티(Wallet, WalletTransaction, Charge) 기준 스키마
-- 인출(CASH_OUT) · 회원 복제본은 엔티티가 생길 때 다음 버전으로 추가한다.
-- enum 칸에는 CHECK를 두지 않는다 (market V1과 같은 규칙)

create table wallet (
    id          bigint generated by default as identity,
    wallet_type varchar(20)    not null,
    member_id   bigint,
    balance     numeric(19, 0) not null,
    version     bigint,
    created_at  timestamp(6),
    updated_at  timestamp(6),
    constraint pk_wallet primary key (id),
    constraint uk_wallet_member_id unique (member_id),
    -- 회원 지갑은 member_id가 꼭 있고, 시스템 지갑(HOLDING · REVENUE)은 없다
    constraint ck_wallet_member_id check ((wallet_type = 'MEMBER') = (member_id is not null))
);

-- 시스템 지갑은 종류별로 하나만
create unique index uk_wallet_system_type on wallet (wallet_type) where wallet_type <> 'MEMBER';

create table wallet_transaction (
    id                bigint generated by default as identity,
    wallet_id         bigint         not null,
    ref_type          varchar(255)   not null,
    ref_id            bigint         not null,
    ref_occurred_time timestamp(6)   not null,
    status            varchar(255)   not null,
    amount            numeric(19, 0) not null,
    balance_after     numeric(19, 0) not null,
    created_at        timestamp(6),
    updated_at        timestamp(6),
    constraint pk_wallet_transaction primary key (id),
    -- 같은 지갑 · 같은 거래 유형 · 같은 대상은 한 번만 (중복 결제 · 환불 · 정산 방지)
    constraint uk_wallet_transaction_ref unique (wallet_id, ref_type, ref_id),
    constraint fk_wallet_transaction_wallet foreign key (wallet_id) references wallet (id)
);

create table charge (
    id                 bigint generated by default as identity,
    wallet_id          bigint         not null,
    charge_type        varchar(255)   not null,
    pg_order_no        varchar(64),
    amount             numeric(19, 0) not null,
    status             varchar(255)   not null,
    pg_payment_key_enc varchar(1024),
    approved_at        timestamp(6),
    canceled_at        timestamp(6),
    created_at         timestamp(6),
    updated_at         timestamp(6),
    constraint pk_charge primary key (id),
    constraint uk_charge_type_pg_order_no unique (charge_type, pg_order_no),
    constraint fk_charge_wallet foreign key (wallet_id) references wallet (id)
);

-- 회원의 충전 조회 (charge → wallet 조인)
create index idx_charge_wallet_id on charge (wallet_id);

-- 시스템 지갑: 앱 코드가 아니라 여기서 한 번만 만든다
insert into wallet (wallet_type, member_id, balance, version, created_at, updated_at)
values ('HOLDING', null, 0, 0, now(), now()),
       ('REVENUE', null, 0, 0, now(), now());
