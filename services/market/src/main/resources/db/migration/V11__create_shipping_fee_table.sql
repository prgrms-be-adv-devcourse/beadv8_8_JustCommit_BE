-- 배송비 요금표 (#589)

-- 택배사(404-express)가 요금표를 바꿀 때마다 웹훅 · 버전 대사로 받은 요금표 전체를 버전별 한 행으로 쌓는다.
-- 주문 배송비는 가장 높은 버전으로 계산한다 (받은 뒤 생성되는 주문부터, 이미 만든 주문의 배송비는 그대로).
-- 우편번호 구간은 [{"from":"63000","to":"63644","name":"제주특별자치도"}, ...] 형식 그대로 둔다
create table shipping_fee_table (
    id                 bigint generated by default as identity,
    version            integer        not null,
    courier_updated_at timestamp(6)   not null,
    base_fee           numeric(19, 0) not null,
    jeju_surcharge     numeric(19, 0) not null,
    remote_surcharge   numeric(19, 0) not null,
    jeju_zipcodes      jsonb          not null,
    remote_zipcodes    jsonb          not null,
    created_at         timestamp(6),
    updated_at         timestamp(6),
    constraint pk_shipping_fee_table primary key (id),
    constraint uk_shipping_fee_table_version unique (version)
);
