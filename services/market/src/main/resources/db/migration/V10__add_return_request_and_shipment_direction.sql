-- 반품 신청 (#382)

-- 배송 방향: 가는 길(OUTBOUND) 배송은 판매자 주문당 1개, 반품(RETURN) 배송은 주문상품마다 새로 만들어 여러 개.
-- 기존 행은 모두 가는 길이다
alter table shipment
    add column direction varchar(20) not null default 'OUTBOUND';

alter table shipment
    drop constraint uk_shipment_seller_order_id;

create unique index uk_shipment_seller_order_id_outbound on shipment (seller_order_id) where direction = 'OUTBOUND';

-- 주문상품 하나에 반품 신청은 한 번 (거절, 완료된 신청도 남겨 다시 신청하지 못하게 한다).
-- V5 이후 테이블(shipment_cancel_result 등)처럼 외래 키는 두지 않는다
create table return_request (
    id                  bigint generated by default as identity,
    order_item_id       bigint        not null,
    seller_order_id     bigint        not null,
    reason              varchar(30)   not null,
    reason_detail       varchar(500),
    status              varchar(20)   not null,
    decided_by          varchar(20),
    requested_at        timestamp(6)  not null,
    decided_at          timestamp(6),
    return_shipping_fee numeric(19, 0),
    shipment_id         bigint,
    created_at          timestamp(6),
    updated_at          timestamp(6),
    constraint pk_return_request primary key (id),
    constraint uk_return_request_order_item_id unique (order_item_id)
);

create index idx_return_request_seller_order_id on return_request (seller_order_id);
