-- 판매자 평가 리뷰 (#582)

-- 판매자 주문 하나에 리뷰는 한 번. 삭제(deleted_at)한 리뷰도 행을 남겨 다시 쓰지 못하게 한다 (유니크는 삭제 여부와 무관).
-- seller_order_id는 엔티티가 연관관계 없이 번호로 갖고 있어 외래 키를 두지 않는다.
-- order_id, buyer_id, seller_id는 작성 시점의 값을 복사해 둔다
create table review (
    id              bigint generated by default as identity,
    seller_order_id bigint        not null,
    order_id        bigint        not null,
    buyer_id        bigint        not null,
    seller_id       bigint        not null,
    rating          numeric(2, 1) not null,
    content         varchar(300)  not null,
    deleted_at      timestamp(6),
    created_at      timestamp(6),
    updated_at      timestamp(6),
    constraint pk_review primary key (id),
    constraint uk_review_seller_order_id unique (seller_order_id)
);

create index idx_review_seller_id_created_at on review (seller_id, created_at desc);
create index idx_review_buyer_id_created_at on review (buyer_id, created_at desc);

-- 리뷰 태그. 리뷰 엔티티에 딸린 값이라 review_id에 외래 키를 둔다
create table review_tag (
    review_id bigint      not null,
    tag       varchar(30) not null,
    constraint pk_review_tag primary key (review_id, tag),
    constraint fk_review_tag_review foreign key (review_id) references review (id)
);
