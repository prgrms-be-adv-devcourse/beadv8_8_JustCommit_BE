-- market 서비스 V1: 지금 엔티티(Cart, CartItem, Orders, SellerOrder, OrdersItem, Shipment) 기준 스키마
-- 회원 복제본(#275) · outbox(#277) · 배송비 요금표는 엔티티가 생길 때 다음 버전으로 추가한다.
-- enum 칸에는 CHECK를 두지 않는다: enum 값을 추가할 때마다 제약을 고쳐야 해서 (노션 정책 10.12)

create table cart (
    id         bigint generated by default as identity,
    member_id  bigint not null,
    created_at timestamp(6),
    updated_at timestamp(6),
    constraint pk_cart primary key (id),
    constraint uk_cart_member_id unique (member_id)
);

create table cart_item (
    id         bigint generated by default as identity,
    cart_id    bigint not null,
    product_id bigint not null,
    price      numeric(19, 0) not null,
    created_at timestamp(6),
    updated_at timestamp(6),
    constraint pk_cart_item primary key (id),
    constraint uk_cart_item_cart_product unique (cart_id, product_id),
    constraint fk_cart_item_cart foreign key (cart_id) references cart (id)
);

create table orders (
    id              bigint generated by default as identity,
    order_no        varchar(30) not null,
    buyer_id        bigint not null,
    total_amount    numeric(19, 0) not null,
    recipient_name  varchar(255) not null,
    recipient_phone varchar(255) not null,
    zipcode         varchar(255) not null,
    ship_address1   varchar(255) not null,
    ship_address2   varchar(255),
    item_count      integer not null,
    status          varchar(255) not null,
    created_at      timestamp(6),
    updated_at      timestamp(6),
    constraint pk_orders primary key (id),
    constraint uk_orders_order_no unique (order_no)
);

-- 구매자 주문 목록, 결제 대기 만료 스케줄러
create index idx_orders_buyer_id on orders (buyer_id);
create index idx_orders_status_created_at on orders (status, created_at);

create table seller_order (
    id                     bigint generated by default as identity,
    order_id               bigint not null,
    seller_id              bigint not null,
    total_amount           numeric(19, 0) not null,
    settlement_base_amount numeric(19, 0) not null,
    shipping_fee           numeric(19, 0) not null,
    confirmed_at           timestamp(6),
    created_at             timestamp(6),
    updated_at             timestamp(6),
    constraint pk_seller_order primary key (id),
    constraint uk_seller_order_order_seller unique (order_id, seller_id),
    constraint fk_seller_order_orders foreign key (order_id) references orders (id)
);

-- 판매자 주문 목록
create index idx_seller_order_seller_id on seller_order (seller_id);

create table orders_item (
    id              bigint generated by default as identity,
    seller_order_id bigint not null,
    product_id      bigint not null,
    product_name    varchar(255) not null,
    price           numeric(19, 0) not null,
    status          varchar(255) not null,
    created_at      timestamp(6),
    updated_at      timestamp(6),
    constraint pk_orders_item primary key (id),
    constraint fk_orders_item_seller_order foreign key (seller_order_id) references seller_order (id)
);

create index idx_orders_item_seller_order_id on orders_item (seller_order_id);

-- seller_order_id는 엔티티가 연관관계 없이 Long으로 갖고 있어 FK를 두지 않는다
create table shipment (
    id                   bigint generated by default as identity,
    seller_order_id      bigint not null,
    courier_order_no     varchar(30),
    tracking_no          varchar(255),
    status               varchar(255) not null,
    item_summary         varchar(255),
    booked_at            timestamp(6),
    picked_up_at         timestamp(6),
    in_transit_at        timestamp(6),
    delivered_at         timestamp(6),
    cancelled_at         timestamp(6),
    courier_cancelled_at timestamp(6),
    version              bigint not null,
    created_at           timestamp(6),
    updated_at           timestamp(6),
    constraint pk_shipment primary key (id),
    constraint uk_shipment_seller_order_id unique (seller_order_id),
    constraint uk_shipment_courier_order_no unique (courier_order_no),
    constraint uk_shipment_tracking_no unique (tracking_no)
);

-- 택배 예약 · 취소 큐 스케줄러
create index idx_shipment_status_created_at on shipment (status, created_at);
