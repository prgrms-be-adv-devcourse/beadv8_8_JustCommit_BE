-- market V6: 택배 취소 큐 (#490, ADR 0025)
-- 취소 API는 배송을 CANCEL_PENDING + 누른 시각으로 기록만 하고, 택배 취소 큐가 택배사에 보낸다.
-- 배송 상태는 문자열 칸이라 새 상태(CANCEL_PENDING · CANCEL_LOCKED)에 스키마 변경은 필요 없다.
alter table shipment
    -- 구매자가 취소를 누른 시각. 택배사는 이 시각의 기사 거리로 판정한다 (재시도해도 같은 값을 보냄)
    add column cancel_requested_at timestamp(6),
    -- 택배 예약 · 취소 큐의 마지막 실패 원인 (Outbox · 토큰 폐기 재처리와 같은 방식, 성공하면 비움)
    add column last_error          varchar(500);

-- 택배 취소 큐가 CANCEL_PENDING 배송 중 시도할 때가 된 것만 찾는다
create index idx_shipment_cancel_pending_next_attempt_at on shipment (next_attempt_at) where status = 'CANCEL_PENDING';

-- 택배 취소 결과: 택배 취소 큐가 배송 상태와 같은 트랜잭션에 한 건 남기고, 주문 Saga 복구가 읽어 환불 · 되돌림을 한다
create table shipment_cancel_result (
    id              bigint generated by default as identity,
    shipment_id     bigint      not null,
    seller_order_id bigint      not null,
    -- CANCELLED(취소됨) · LOCKED(취소 불가: 기사 2km 안)
    result          varchar(20) not null,
    -- 취소는 됐지만 이미 수거돼 택배사가 판매자에게 반송하는지 (returning은 PostgreSQL 예약어라 피함)
    courier_return  boolean     not null default false,
    -- 택배사 결과를 받은 시각
    decided_at      timestamp(6) not null,
    -- 주문 Saga가 처리한 시각. 비어 있으면 아직 처리 전
    processed_at    timestamp(6),
    created_at      timestamp(6),
    updated_at      timestamp(6),
    constraint pk_shipment_cancel_result primary key (id),
    -- 배송 하나의 취소 결과는 한 번만
    constraint uk_shipment_cancel_result_shipment_id unique (shipment_id)
);

-- 주문 Saga가 아직 처리하지 않은 결과만 찾는다
create index idx_shipment_cancel_result_unprocessed on shipment_cancel_result (id) where processed_at is null;
