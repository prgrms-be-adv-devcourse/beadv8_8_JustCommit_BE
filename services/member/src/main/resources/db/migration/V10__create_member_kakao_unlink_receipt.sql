-- 카카오 연결 해제 웹훅 수신 기록 (#422). 처리 흐름 → docs/flows/signup-and-replica.md 「카카오 연결 해제 웹훅」
-- 요청마다 한 행. 받을 때는 기록만 하고, 스케줄러가 단계(status)를 따라 처리한다.
-- - provider_id: 카카오 회원번호. 잘못된 요청(IGNORED)은 비어 있을 수 있음
-- - member_id · unlink_version: INACTIVE로 바꿀 때의 회원과 폐기 후 인증 버전 (연결 해제 상태)
-- - handles_withdrawal: 이 연결 해제 상태의 자동 탈퇴 처리 기록인지 (완료 여부가 아님, 완료는 status)
-- - attempt_no: 처리권. 확보 · 운영자 재개마다 1씩 올리고 되돌리지 않음. 결과 반영은 자기 번호와 상태가 그대로일 때만
-- - failure_count: 지금 단계의 실패 횟수. 단계가 넘어가면 0
-- 시각은 DB 시각(Instant)이라 WITH TIME ZONE을 쓴다.
CREATE TABLE member_kakao_unlink_receipt
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id        VARCHAR(20),
    referrer_type      VARCHAR(40),
    received_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status             VARCHAR(20)                 NOT NULL,
    resume_state       VARCHAR(20),
    member_id          BIGINT,
    unlink_version     INTEGER,
    handles_withdrawal BOOLEAN                     NOT NULL DEFAULT FALSE,
    attempt_no         INTEGER                     NOT NULL DEFAULT 0,
    lease_until        TIMESTAMP(6) WITH TIME ZONE,
    failure_count      INTEGER                     NOT NULL DEFAULT 0,
    next_attempt_at    TIMESTAMP(6) WITH TIME ZONE,
    last_error         VARCHAR(50),
    created_at         TIMESTAMP(6)                NOT NULL,
    updated_at         TIMESTAMP(6)                NOT NULL,
    CONSTRAINT fk_member_kakao_unlink_receipt_member FOREIGN KEY (member_id) REFERENCES member (id),
    CONSTRAINT ck_member_kakao_unlink_receipt_status CHECK (status IN
        ('PENDING', 'INACTIVATED', 'NOTICE_PENDING', 'DONE', 'IGNORED', 'INVALIDATED', 'DUPLICATE', 'FAILED')),
    CONSTRAINT ck_member_kakao_unlink_receipt_resume CHECK (resume_state IN ('PENDING', 'INACTIVATED', 'NOTICE_PENDING')),
    -- FAILED일 때만 재개할 단계가 있다
    CONSTRAINT ck_member_kakao_unlink_receipt_failed CHECK ((status = 'FAILED') = (resume_state IS NOT NULL)),
    -- 회원번호 없이 처리 단계로 갈 수 없다 (잘못된 요청은 IGNORED로만 저장)
    CONSTRAINT ck_member_kakao_unlink_receipt_provider CHECK (status = 'IGNORED' OR provider_id IS NOT NULL),
    -- 자동 탈퇴 처리 기록은 회원과 연결 해제 상태가 정해진 기록만
    CONSTRAINT ck_member_kakao_unlink_receipt_withdrawal CHECK (
        NOT handles_withdrawal OR (member_id IS NOT NULL AND unlink_version IS NOT NULL)),
    CONSTRAINT ck_member_kakao_unlink_receipt_version CHECK (unlink_version > 0),
    CONSTRAINT ck_member_kakao_unlink_receipt_attempt CHECK (attempt_no >= 0),
    CONSTRAINT ck_member_kakao_unlink_receipt_failure CHECK (failure_count >= 0)
);

-- 같은 회원 · 같은 연결 해제 상태에 자동 탈퇴 처리 기록은 하나 (정상 경로는 회원 잠금 안에서 먼저 조회, 이 인덱스는 마지막 방어)
CREATE UNIQUE INDEX uk_member_kakao_unlink_receipt_withdrawal
    ON member_kakao_unlink_receipt (member_id, unlink_version) WHERE handles_withdrawal;

-- 스케줄러: 처리할 단계 중 다음 시도 시각이 지난 기록
CREATE INDEX idx_member_kakao_unlink_receipt_work ON member_kakao_unlink_receipt (status, next_attempt_at);

-- 재로그인: 회원번호로 미처리 기록을 찾아 무효화 (회원 연결 전 기록 포함)
CREATE INDEX idx_member_kakao_unlink_receipt_provider ON member_kakao_unlink_receipt (provider_id, status);

-- 회원별 조회 · FK 검사용 (PostgreSQL은 FK에 인덱스를 자동으로 만들지 않음)
CREATE INDEX idx_member_kakao_unlink_receipt_member_id ON member_kakao_unlink_receipt (member_id);
