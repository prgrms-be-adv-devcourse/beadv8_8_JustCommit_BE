-- member 서비스 초기 테이블: 회원 · 판매자 · 배송지
-- 엔티티(Member · Seller · Address)와 맞춘다. JPA는 ddl-auto: validate로 검사만 한다.

CREATE TABLE member
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email              VARCHAR(100),
    password           VARCHAR(100),
    nickname           VARCHAR(20)  NOT NULL,
    phone              VARCHAR(20)  NOT NULL,
    role               VARCHAR(20)  NOT NULL,
    provider           VARCHAR(20)  NOT NULL,
    provider_id        VARCHAR(100),
    bank_code          VARCHAR(10)  NOT NULL,
    account_no_enc     VARCHAR(255) NOT NULL,
    account_holder     VARCHAR(50)  NOT NULL,
    account_updated_at TIMESTAMP(6) NOT NULL,
    status             VARCHAR(20)  NOT NULL,
    created_at         TIMESTAMP(6) NOT NULL,
    updated_at         TIMESTAMP(6) NOT NULL,
    -- 가입 서비스가 이 제약 이름으로 중복 항목을 구분한다 (이름 변경 금지)
    CONSTRAINT uk_member_email UNIQUE (email),
    CONSTRAINT uk_member_nickname UNIQUE (nickname),
    CONSTRAINT uk_member_phone UNIQUE (phone),
    CONSTRAINT uk_member_provider UNIQUE (provider, provider_id),
    CONSTRAINT ck_member_role CHECK (role IN ('MEMBER', 'SELLER', 'ADMIN')),
    CONSTRAINT ck_member_provider CHECK (provider IN ('LOCAL', 'KAKAO', 'NAVER')),
    CONSTRAINT ck_member_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'DELETED'))
);

-- 판매자: 회원과 1:1, 회원 id를 그대로 PK로 사용
CREATE TABLE seller
(
    member_id  BIGINT PRIMARY KEY,
    intro      VARCHAR(500),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_seller_member FOREIGN KEY (member_id) REFERENCES member (id)
);

-- 배송지: 회원당 기본 배송지 1개는 서비스에서 보장 (회원 행 잠금)
CREATE TABLE address
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id       BIGINT       NOT NULL,
    recipient_name  VARCHAR(20)  NOT NULL,
    recipient_phone VARCHAR(11)  NOT NULL,
    zipcode         VARCHAR(5)   NOT NULL,
    address1        VARCHAR(200) NOT NULL,
    address2        VARCHAR(100),
    address_name    VARCHAR(20),
    is_default      BOOLEAN      NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_address_member FOREIGN KEY (member_id) REFERENCES member (id)
);

-- 회원별 배송지 조회 · FK 검사용 (PostgreSQL은 FK에 인덱스를 자동으로 만들지 않음)
CREATE INDEX idx_address_member_id ON address (member_id);