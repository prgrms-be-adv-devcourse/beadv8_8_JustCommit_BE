-- 회원 탈퇴 (#407): 익명화할 컬럼의 NOT NULL 해제 + 재가입 제한용 탈퇴 기록
-- 탈퇴하면 개인정보 컬럼을 NULL로 바꾼다 (docs/flows/signup-and-replica.md 「익명화」).
-- email · password · provider_id · account_hash는 V1 · V6부터 NULL 허용이라 바꾸지 않는다.
-- UNIQUE 제약은 그대로 둔다. PostgreSQL UNIQUE는 NULL을 여러 개 허용해 탈퇴 회원끼리 충돌하지 않는다.
ALTER TABLE member
    ALTER COLUMN nickname DROP NOT NULL,
    ALTER COLUMN phone DROP NOT NULL,
    ALTER COLUMN bank_code DROP NOT NULL,
    ALTER COLUMN account_no_enc DROP NOT NULL,
    ALTER COLUMN account_holder DROP NOT NULL,
    ALTER COLUMN account_updated_at DROP NOT NULL;

-- 탈퇴 기록: 이메일 · 휴대폰 HMAC(MemberHmac, hex 64글자)과 탈퇴 시각만 둔다. member_id는 넣지 않는다.
-- 30일 판정은 DB 시각(clock_timestamp) 기준이라, V4처럼 DB 시각은 WITH TIME ZONE을 쓴다.
-- 30일 뒤 재가입 · 재탈퇴하면 같은 해시가 다시 생길 수 있어 해시에는 UNIQUE를 걸지 않는다.
CREATE TABLE member_withdrawal_record
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_hash   VARCHAR(64)                 NOT NULL,
    phone_hash   VARCHAR(64)                 NOT NULL,
    withdrawn_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at   TIMESTAMP(6)                NOT NULL,
    updated_at   TIMESTAMP(6)                NOT NULL
);

-- 가입 때 재가입 제한 조회
CREATE INDEX idx_member_withdrawal_record_email_hash ON member_withdrawal_record (email_hash);
CREATE INDEX idx_member_withdrawal_record_phone_hash ON member_withdrawal_record (phone_hash);
-- 30일 지난 기록 정리 스케줄러
CREATE INDEX idx_member_withdrawal_record_withdrawn_at ON member_withdrawal_record (withdrawn_at);
