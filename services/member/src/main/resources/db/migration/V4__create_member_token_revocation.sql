-- 회원 토큰 폐기 작업 (#409).
-- 비밀번호 변경 · 탈퇴 트랜잭션에서 함께 저장하고, 커밋 뒤 Redis(auth:revoked-member)에 폐기 시각을 기록한다.
-- Redis 기록에 실패한 작업은 재처리 스케줄러가 같은 Lua로 다시 기록한다.
-- 폐기 시각 · 보관 기한 · 다음 시도 시각은 DB 시각(Instant)이라 시간대 없는 TIMESTAMP가 아니라 WITH TIME ZONE을 쓴다.
CREATE TABLE member_token_revocation
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id       BIGINT                      NOT NULL,
    reason          VARCHAR(20)                 NOT NULL,
    token_version   INTEGER                     NOT NULL,
    cutoff_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    retain_until    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status          VARCHAR(20)                 NOT NULL,
    attempt_count   INTEGER                     NOT NULL,
    next_attempt_at TIMESTAMP(6) WITH TIME ZONE,
    last_error      VARCHAR(500),
    created_at      TIMESTAMP(6)                NOT NULL,
    updated_at      TIMESTAMP(6)                NOT NULL,
    CONSTRAINT fk_member_token_revocation_member FOREIGN KEY (member_id) REFERENCES member (id),
    CONSTRAINT ck_member_token_revocation_reason CHECK (reason IN ('PASSWORD_CHANGED', 'WITHDRAWN')),
    CONSTRAINT ck_member_token_revocation_status CHECK (status IN ('PENDING', 'RECORDED', 'EXPIRED')),
    CONSTRAINT ck_member_token_revocation_version CHECK (token_version > 0),
    CONSTRAINT ck_member_token_revocation_attempt CHECK (attempt_count >= 0),
    CONSTRAINT ck_member_token_revocation_retain CHECK (retain_until > cutoff_at)
);

-- 재처리 스케줄러: PENDING 중 다음 시도 시각이 지난 작업
CREATE INDEX idx_member_token_revocation_retry ON member_token_revocation (status, next_attempt_at);

-- 회원별 조회 · FK 검사용 (PostgreSQL은 FK에 인덱스를 자동으로 만들지 않음)
CREATE INDEX idx_member_token_revocation_member_id ON member_token_revocation (member_id);