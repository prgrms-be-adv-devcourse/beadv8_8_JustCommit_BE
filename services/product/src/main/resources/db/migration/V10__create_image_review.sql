-- 사진 검수 기록 (docs/flows/image-review.md). 검수 버전마다 한 행
-- 등록 · 수정 트랜잭션에서 REQUESTED로 만들고, 검수 리스너가 결과를 채워 DONE (그사이 다시 수정되면 STALE)
-- 외부 API 오류면 ENGINE_ERROR로 두고 재처리 스케줄러가 5분 뒤 다시 검수 (최대 3회, 그래도 실패하면 관리자 확인)
create table image_review (
    id             bigint generated by default as identity,
    product_id     bigint       not null,
    review_version integer      not null,
    seller_id      bigint       not null,
    scope          varchar(20)  not null,   -- FULL(사진 검수부터) · TEXT_ONLY(글 검사만)
    status         varchar(20)  not null,   -- REQUESTED · ENGINE_ERROR · DONE · STALE
    decision       varchar(20),             -- APPROVED · REJECTED · MANUAL
    reject_reason  varchar(30),
    manual_reason  varchar(30),
    detail         varchar(200),            -- 걸린 금지 품종 · 단어, 불일치 학명 (관리자 화면)
    engine_result  text,                    -- 엔진 결과 JSON (유해 여부 · 식물 여부 · 판매 형태 · 후보 · 확신도)
    error_message  varchar(500),            -- 외부 API 실패 원인
    reviewed_at    timestamp(6),            -- 판정 시각 (관리자 확인 기한 12 · 24시간의 시작)
    retry_count    integer      not null default 0,   -- 엔진 오류 재처리 횟수
    next_retry_at  timestamp(6),            -- 엔진 오류 다음 재처리 시각
    created_at     timestamp(6),
    updated_at     timestamp(6),
    constraint pk_image_review primary key (id),
    constraint uk_image_review_product_version unique (product_id, review_version)
);

-- 하루 사진 검수 횟수 · 최근 7일 반려 수 (판매자별)
create index idx_image_review_seller_created on image_review (seller_id, created_at);
create index idx_image_review_seller_reviewed on image_review (seller_id, reviewed_at);

-- 엔진 오류 재처리 대상 (재처리 스케줄러)
create index idx_image_review_status_next_retry on image_review (status, next_retry_at);
