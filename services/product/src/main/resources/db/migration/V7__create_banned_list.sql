-- product 서비스 V7: 판매 금지 목록 (#342, docs/flows/image-review.md · 정책 3.17)
-- 품종 목록(species)과 따로 두고 학명으로 대조한다. 데이터는 V8, 바꿀 때는 새 버전 파일로
-- enum 칸에는 CHECK를 두지 않는다 (V1과 같은 규칙)

create table banned_species (
    id              bigint generated by default as identity,
    scientific_name varchar(100) not null,   -- 법령 학명
    taxon_rank      varchar(10)  not null,   -- GENUS · SPECIES · INFRA(변종 · 아종)
    korean_name     varchar(50)  not null,
    basis           varchar(20)  not null,   -- KR_ENDANGERED_I · KR_ENDANGERED_II · NARCOTIC · INVASIVE
    source          varchar(255) not null,   -- 근거 법령
    memo            varchar(500),
    constraint pk_banned_species primary key (id),
    constraint uk_banned_species_scientific_name unique (scientific_name)
);

create table banned_species_alias (
    id                bigint generated by default as identity,
    banned_species_id bigint       not null,
    alias             varchar(100) not null,
    alias_type        varchar(20)  not null,   -- SCIENTIFIC(학명 동의어) · KOREAN(한글 별칭)
    constraint pk_banned_species_alias primary key (id),
    constraint uk_banned_species_alias unique (banned_species_id, alias),
    constraint fk_banned_species_alias_banned_species foreign key (banned_species_id) references banned_species (id)
);

create table banned_keyword (
    id           bigint generated by default as identity,
    keyword      varchar(50)  not null,
    keyword_type varchar(20)  not null,   -- BANNED(반려) · REVIEW(관리자 확인) · EXCEPTION(넘어감)
    reason       varchar(500),
    constraint pk_banned_keyword primary key (id),
    constraint uk_banned_keyword_keyword unique (keyword)
);
