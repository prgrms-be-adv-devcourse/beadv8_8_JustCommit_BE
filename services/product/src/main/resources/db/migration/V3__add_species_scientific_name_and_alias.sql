-- 판매 금지 품종은 species와 따로 banned_species로 관리하기로 해서 is_banned를 없앤다 (정책 3.15 · 3.17). banned_species는 이미지 검수에서 추가한다.

alter table species add column scientific_name varchar(255);
alter table species drop column is_banned;

-- 같은 별칭이 여러 품종에 걸릴 수 있어 별칭만으로는 unique가 아니다
create table species_alias (
    id         bigint generated by default as identity,
    species_id bigint not null,
    alias      varchar(255) not null,
    source     varchar(20) not null,
    constraint pk_species_alias primary key (id),
    constraint uk_species_alias_species_id_alias unique (species_id, alias),
    constraint fk_species_alias_species foreign key (species_id) references species (id)
);
