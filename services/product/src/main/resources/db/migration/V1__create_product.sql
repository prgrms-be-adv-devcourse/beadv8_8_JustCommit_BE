-- product 서비스 V1: 지금 엔티티(Species, SpeciesImage, Product, ProductImage) 기준 스키마
-- 품종 학명 · 별칭(#264), 회원 복제본 · outbox · 예약 기록 · 사진 검수는 엔티티가 생길 때 다음 버전으로 추가한다.
-- 품종 데이터(db/data/species.sql)는 아직 Flyway가 아니라 배포 스크립트로 넣는다.
-- enum 칸에는 CHECK를 두지 않는다: enum 값을 추가할 때마다 제약을 고쳐야 해서 (market V1과 같은 규칙)

create table species (
    id         bigint generated by default as identity,
    name       varchar(255) not null,
    light      varchar(20),
    watering   varchar(30),
    difficulty varchar(20),
    color      varchar(20),
    category   varchar(30),
    is_banned  boolean not null,
    created_at timestamp(6),
    updated_at timestamp(6),
    constraint pk_species primary key (id),
    constraint uk_species_name unique (name)
);

create table species_image (
    id         bigint generated by default as identity,
    species_id bigint not null,
    s3_url     varchar(255) not null,
    sort_order integer not null,
    constraint pk_species_image primary key (id),
    constraint fk_species_image_species foreign key (species_id) references species (id)
);

-- 품종 목록 · 상세에서 사진을 품종별로 묶어 읽음 (@BatchSize)
create index idx_species_image_species_id on species_image (species_id);

create table product (
    id                bigint generated by default as identity,
    species_id        bigint not null,
    seller_id         bigint not null,
    title             varchar(100) not null,
    description       text,
    price             numeric(19, 0) not null,
    height_cm         integer,
    pot_size          varchar(20),
    grow_note         varchar(500),
    status            varchar(20) not null,
    is_hidden         boolean not null,
    reserved_order_id bigint,
    created_at        timestamp(6),
    updated_at        timestamp(6),
    constraint pk_product primary key (id),
    constraint fk_product_species foreign key (species_id) references species (id)
);

-- 엔티티 @Index와 같은 이름
create index idx_product_species on product (species_id);
create index idx_product_seller on product (seller_id);
create index idx_product_status on product (status);
create index idx_product_reserved_order on product (reserved_order_id);

create table product_image (
    id         bigint generated by default as identity,
    product_id bigint not null,
    s3_url     varchar(255) not null,
    sort_order integer not null,
    constraint pk_product_image primary key (id),
    constraint fk_product_image_product foreign key (product_id) references product (id)
);

-- 상품 목록 · 상세에서 사진을 상품별로 묶어 읽음 (@BatchSize)
create index idx_product_image_product_id on product_image (product_id);
