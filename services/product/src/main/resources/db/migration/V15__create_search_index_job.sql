-- product 서비스 V15: 상품 검색 전체 색인 · 무중단 재색인 작업 기록 (#563, docs/flows/search-recommend.md 「매핑 변경」)
-- 작업마다 한 행. 진행 상태 조회 API가 읽고, 서버를 다시 띄워도 남는다.
-- 끝나지 않은 행(finished_at이 NULL)은 전체에서 하나만 둘 수 있어, 여러 서버에서 동시에 요청해도 색인 작업은 하나만 돈다 (잠금 역할)
create table search_index_job (
    id                  bigint generated by default as identity,
    type                varchar(20)  not null,   -- REINDEX_ALL(전체 색인) · REBUILD(무중단 재색인)
    phase               varchar(20)  not null,   -- QUEUED · FILLING · SWITCHING_ALIAS · CATCHING_UP · CLEANING_UP · COMPLETED · FAILED
    failed_phase        varchar(20),             -- 실패했을 때 어느 단계였는지
    worker              varchar(100),            -- 실행한 서버(호스트 이름)
    previous_index      varchar(50),             -- 재색인 전 alias가 가리키던 인덱스
    next_index          varchar(50),             -- 재색인으로 새로 채우는 인덱스
    total_count         bigint,                  -- 시작할 때 상품 행 수 (진행률 계산용, 그사이 등록된 상품은 빠짐)
    processed_count     bigint       not null default 0,   -- 채우기(전체 색인)에서 보낸 수 (색인 + 삭제)
    skipped_count       bigint       not null default 0,   -- 그중 같거나 더 새 버전이 이미 있어 건너뛴 수
    failed_count        bigint       not null default 0,   -- 그중 OpenSearch가 거절한 수
    caught_up_processed bigint       not null default 0,   -- 따라잡기에서 보낸 수 (재색인만)
    caught_up_skipped   bigint       not null default 0,
    caught_up_failed    bigint       not null default 0,
    previous_deleted    boolean,                 -- 재색인이 옛 인덱스를 지웠는지 (false면 직접 지움)
    failure_reason      varchar(500),
    heartbeat_at        timestamp(6) not null,   -- 실행 중인 서버가 배치마다 갱신. 오래 멈추면 죽은 작업으로 보고 실패 처리
    started_at          timestamp(6),
    finished_at         timestamp(6),
    created_at          timestamp(6) not null,
    constraint pk_search_index_job primary key (id)
);

-- 끝나지 않은 작업은 하나만 (상수 식 유니크 + 부분 인덱스). 두 번째 INSERT는 유니크 위반 → 409 SEARCH_INDEXING_IN_PROGRESS
create unique index uk_search_index_job_running on search_index_job ((true)) where finished_at is null;
