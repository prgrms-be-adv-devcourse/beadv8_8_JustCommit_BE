-- notification 서비스 V1: 지금 엔티티(Notification) 기준 스키마
-- 알림은 지우지 않고 보관한다.
-- enum 칸에는 CHECK를 두지 않는다: enum 값을 추가할 때마다 제약을 고쳐야 해서 (market V1과 같은 규칙)

create table notification (
    id              bigint generated by default as identity,
    member_id       bigint not null,
    type            varchar(30) not null,
    message         varchar(255) not null,
    order_id        bigint,
    seller_order_id bigint,
    item_summary    varchar(255),
    is_read         boolean not null,
    read_at         timestamp(6),
    -- Kafka가 같은 메시지를 두 번 줘도 알림이 한 건만 생기게 한다
    event_key       varchar(100) not null,
    created_at      timestamp(6),
    updated_at      timestamp(6),
    constraint pk_notification primary key (id),
    constraint uk_notification_event_key unique (event_key)
);

-- 내 알림 목록(읽음 여부 필터 · 최신순) · 안 읽은 개수
create index idx_notification_member_read_created on notification (member_id, is_read, created_at);
